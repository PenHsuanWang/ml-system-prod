"""Consumed workflow ports; implementations satisfy these structurally."""

from collections.abc import Callable, Iterable
from typing import Protocol

from src.domain.ingestion.models import (
    AdapterDescriptor,
    BatchExtraction,
    ExtractionLimits,
    IngestionClaim,
    IngestionJob,
    PublicationIntent,
    RawSnapshot,
    SourceDefinition,
    StagedBatch,
)
from src.domain.ml import Actor


class AcquisitionControl(Protocol):
    def check(self) -> None: ...


class BatchStager(Protocol):
    def stage(
        self, extraction: BatchExtraction, chunks: Iterable[bytes], control: AcquisitionControl
    ) -> StagedBatch: ...
    def discard(self, staged: StagedBatch) -> None: ...


class BatchSourceAdapter(Protocol):
    def acquire(self, extraction: BatchExtraction, control: AcquisitionControl) -> StagedBatch: ...


class SourceResolver(Protocol):
    def resolve(self, actor: Actor, source_id: str, version: str) -> SourceDefinition: ...
    def for_execution(self, job: IngestionJob) -> SourceDefinition: ...


class SourceAdapterResolver(Protocol):
    def resolve(
        self, adapter_type: str, version: str, capability: str = "batch_extract"
    ) -> BatchSourceAdapter: ...
    def validate_source(self, source: SourceDefinition) -> None: ...


class RawSnapshotPublisher(Protocol):
    def prepare(self, extraction: BatchExtraction, staged: StagedBatch) -> PublicationIntent: ...
    def publish(self, intent: PublicationIntent) -> RawSnapshot: ...
    def lookup(
        self, tenant_id: str, snapshot_id: str, manifest_digest: str
    ) -> RawSnapshot | None: ...
    def verify(self, snapshot: RawSnapshot) -> RawSnapshot: ...
    def discard(self, staged: StagedBatch) -> None: ...


class IngestionJobRepository(Protocol):
    def find_submission(self, actor: Actor, key: str, fingerprint: str) -> IngestionJob | None: ...
    def submit(
        self,
        actor: Actor,
        key: str,
        fingerprint: str,
        source: SourceDefinition,
        limits: ExtractionLimits,
    ) -> IngestionJob: ...
    def get(self, job_id: str) -> IngestionJob: ...
    def cancel(self, actor: Actor, job_id: str) -> IngestionJob: ...
    def claim_next(self, *, job_id: str | None = None) -> IngestionClaim | None: ...
    def heartbeat(self, claim: IngestionClaim) -> IngestionJob: ...
    def stage_complete(self, claim: IngestionClaim, staged: StagedBatch) -> IngestionClaim: ...
    def prepare_publication(
        self, claim: IngestionClaim, intent: PublicationIntent
    ) -> IngestionClaim: ...
    def finish(self, claim: IngestionClaim, snapshot: RawSnapshot) -> IngestionJob: ...
    def fail(self, claim: IngestionClaim, error_code: str, *, retryable: bool) -> IngestionJob: ...
    def reconcile_later(self, claim: IngestionClaim, error_code: str) -> None: ...
    def snapshot(self, actor: Actor, snapshot_id: str) -> RawSnapshot: ...
    def protected_job_ids(self) -> frozenset[str]: ...
    def requeue_reconciliation(self, actor: Actor, job_id: str) -> IngestionJob: ...


# Registration is explicit at Bootstrap; validators never come from request strings.
SourceValidator = Callable[[SourceDefinition], None]
AdapterRegistration = tuple[AdapterDescriptor, BatchSourceAdapter, SourceValidator]
