"""Narrow contracts owned by the training use cases."""

from __future__ import annotations

from typing import Protocol

from src.domain.ml import Actor
from src.domain.training.execution import ExecutionHandle, ExecutionObservation, TrainingOutput
from src.domain.training.models import Attempt, Claim, Job, TrainingCommand


class TrainingRepository(Protocol):
    def find_submission(self, actor: Actor, key: str, fingerprint: str) -> Job | None: ...
    def submit(self, actor: Actor, key: str, request_fingerprint: str,
               spec_json: str, spec_digest: str) -> Job: ...

    def get(self, job_id: str) -> Job: ...
    def attempts(self, job_id: str) -> tuple[Attempt, ...]: ...
    def cancel(self, job_id: str, actor: Actor) -> Job: ...
    def claim(self, command: TrainingCommand) -> Claim: ...
    def execution_started(self, claim: Claim, execution_ref: str) -> None: ...
    def heartbeat(self, claim: Claim) -> Job: ...
    def finish(self, claim: Claim, binding_id: str, evaluation_id: str) -> None: ...
    def stop(self, claim: Claim, code: str, confirmed: bool) -> None: ...
    def prepare_execution(self, claim: Claim, execution_ref: str) -> None: ...
    def checkpoint_phase(self, claim: Claim, phase: str,
                         evidence_json: str | None = None) -> None: ...


class TrainingExecutor(Protocol):
    def prepare(self, spec_json: str, attempt_id: str, owner_token: str) -> ExecutionHandle: ...
    def launch(self, handle: ExecutionHandle) -> None: ...
    def inspect(self, handle: ExecutionHandle) -> ExecutionObservation: ...
    def stop(self, handle: ExecutionHandle) -> bool: ...
    def result(self, handle: ExecutionHandle) -> TrainingOutput | None: ...


class CommandPublisher(Protocol):
    async def publish(self, command: TrainingCommand) -> None: ...


class RecipeResolver(Protocol):
    def resolve(self, intent_json: str, actor: Actor | None = None) -> str: ...
